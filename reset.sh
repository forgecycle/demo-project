#!/usr/bin/env bash
# Reset ForgeCycle's state so the demo can be tested from scratch.
# Run it from anywhere; it always works on this repository.
# It never touches the current branch, your commits, or tracked files.
set -eu

cd "$(dirname "$0")"

# Runtime state (all of it is gitignored).
rm -rf .forgecycle/active.lock
rm -rf .forgecycle/task-runs
rm -rf .forgecycle/roadmap-runs
rm -rf .forgecycle/worktrees
rm -f .forgecycle/adapter-cooldowns.json

# Git's record of the deleted worktrees.
git worktree prune

# Branches ForgeCycle created: forgecycle/task/* and forgecycle/roadmap/*.
git for-each-ref --format='%(refname:short)' 'refs/heads/forgecycle/' |
  while read -r branch; do
    git branch -D "$branch"
  done

# Task files generated by `roadmap decompose` (untracked only, so
# tasks/highlight-moves.md and anything committed stays).
git clean -fdq -- tasks/

echo "ForgeCycle state reset."
